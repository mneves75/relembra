const DEFAULT_RECALL_LIMIT = 50;
const DEFAULT_FIND_LIMIT = 10;
/** The most results one find may return. */
export const MAX_FIND_LIMIT = 100;
/** The most characters a find query or a brief topic may have. */
export const MAX_QUERY_LENGTH = 1_000;

export function createRelembra<Context>(options: RelembraOptions<Context>): Relembra<Context> {
  const { store } = options;
  // Every principal the host's policy gives is checked once, before any operation uses it.
  const policy = async (context: Context): Promise<Principal> =>
    checkPrincipal(await options.policy(context));
  const clock = options.clock ?? systemClock;
  const ids = options.ids ?? randomIds;
  const egress = options.egress ?? identityEgress;
  const retention = checkRetention(options.retention ?? []);

  /**
   * `render()`'s rendering, once the store recorded that `carrier` received every memory it
   * carries. The recording reports the memories redacted by then: a redaction that committed
   * after the read and before the recording could not name the carrier, so the text is not
   * returned and the rendering is made again, at most three times in all.
   */
  async function exposed(
    carrier: Carrier | undefined,
    render: () => Promise<Rendering>,
  ): Promise<Rendering> {
    if (carrier === undefined) return render();
    for (let attempt = 1; ; attempt++) {
      const rendering = await render();
      if (rendering.memoryIds.length === 0) return rendering;
      const memoryIds = [...new Set(rendering.memoryIds)].sort();
      const redacted = await store.recordExposure({ carrier, memoryIds, at: clock.now() });
      if (redacted.length === 0) return rendering;
      if (attempt === MAX_RENDER_ATTEMPTS) throw new ExposureRedactedError();
    }
  }

  /** find for a checked principal: the read checks, then BM25 over its live memories. */
  async function findRanked(principal: Principal, input: FindInput): Promise<Ranked[]> {
    const { scope, query } = input;
    if (scope !== undefined && !principal.readable.includes(scope)) {
      throw new ScopeDeniedError("read");
    }
    const limit = input.limit ?? DEFAULT_FIND_LIMIT;
    if (!Number.isInteger(limit) || limit < 1 || limit > MAX_FIND_LIMIT) {
      throw new RangeError(`find limit must be an integer from 1 to ${MAX_FIND_LIMIT}`);
    }
    if (typeof query !== "string" || query.length > MAX_QUERY_LENGTH) {
      throw new RangeError(`find query must be a string of at most ${MAX_QUERY_LENGTH} characters`);
    }
    const parsed = parseQuery(query);
    // Nothing can match a query without tokens, so the store is not read at all.
    if (parsed.terms.length === 0) return [];
    // Each scope once: a scope listed twice must not count its memories twice in N.
    const scopes = [...new Set(scope === undefined ? principal.readable : [scope])];
    const scores = new Map<MemoryId, number>();
    const memories = await store.findByTerms({
      scopes,
      terms: parsed.terms,
      choose(index) {
        const best = scoreIndex(parsed, index).slice(0, limit);
        for (const { memoryId, score } of best) scores.set(memoryId, score);
        return best.map((scored) => scored.memoryId);
      },
    });
    return memories.map((memory) => ({ memory, score: scores.get(memory.id) as number }));
  }

  return {
    async note(context, input) {
      // Copy every field once, so an accessor cannot answer differently to the checks and the store.
      const { scope, text, opId, pinned = false } = input;
      const principal = await policy(context);
      if (!principal.writable.includes(scope)) throw new ScopeDeniedError("write");
      // Rendering refuses what the rule refuses, so a memory that could never be shown is never stored.
      checkName("scope", scope);
      if (pinned && !(principal.pinnable ?? []).includes(scope)) throw new ScopeDeniedError("pin");
      guardText(text);
      const fence = principal.fence === undefined ? undefined : checkFence(principal.fence);
      const provenance = writerProvenance(principal, input.provenance, opId ?? ids.opId());
      const fingerprint = noteFingerprint({
        scope,
        principalId: principal.id,
        text,
        pinned,
        provenance,
      });
      // Generated before the transaction: no host callback runs while the store is locked.
      const at = clock.now();
      const memoryId = generatedMemoryId(ids);
      return store.transaction(async (tx) => {
        // Current authority first: a stale writer gets no replay of its own committed op either.
        if (fence !== undefined) await enforceFence(tx, fence);
        const prior = await priorOutcome(tx, principal, provenance.opId, fingerprint);
        if (prior !== undefined) {
          // The first commit's outcome; the fingerprint proves every other field is the same.
          const times = await firstTimes(tx, prior);
          return noted(prior.memoryId, scope, prior.seq, pinned, times, text, provenance);
        }
        return commitNote(
          tx,
          { memoryId, scope, principal, pinned, at, text, provenance },
          fingerprint,
        );
      });
    },

    async supersede(context, input) {
      const { memoryId: supersedes, text, opId, pinned = false } = input;
      const principal = await policy(context);
      checkMemoryId(supersedes);
      guardText(text);
      const fence = principal.fence === undefined ? undefined : checkFence(principal.fence);
      const provenance = writerProvenance(principal, input.provenance, opId ?? ids.opId());
      const fingerprint = supersedeFingerprint({
        supersedes,
        principalId: principal.id,
        text,
        pinned,
        provenance,
      });
      const at = clock.now();
      const memoryId = generatedMemoryId(ids);
      return store.transaction(async (tx) => {
        if (fence !== undefined) await enforceFence(tx, fence);
        const prior = await priorOutcome(tx, principal, provenance.opId, fingerprint);
        if (prior !== undefined) {
          const replacement = await tx.memory(prior.memoryId);
          // Current authority over the replacement's scope, as a note's retry checks its scope.
          if (replacement === undefined || !principal.writable.includes(replacement.scope)) {
            throw new ScopeDeniedError("write");
          }
          if (!owns(principal, replacement.scope)) throw new ScopeDeniedError("own");
          return noted(
            prior.memoryId,
            replacement.scope,
            prior.seq,
            pinned,
            await firstTimes(tx, prior),
            text,
            provenance,
          );
        }
        // The replacement lives where the memory it replaces lives.
        const target = visible(principal, await tx.memory(supersedes));
        if (!principal.writable.includes(target.scope)) throw new ScopeDeniedError("write");
        // Superseding hides the target from every reader, so it needs what retracting needs.
        if (!owns(principal, target.scope)) throw new ScopeDeniedError("own");
        if (target.status !== "live") throw new MemoryStateError(target.status);
        if (isSummary(target)) throw new SummarySupersedeError();
        // Nor may it displace, or retract a summary, more trusted than its writes could be.
        const summaries = await liveDerived(tx, target.id);
        enforceCeiling(principal, [target, ...summaries]);
        const pinRights = (principal.pinnable ?? []).includes(target.scope);
        if ((pinned || target.pinned) && !pinRights) throw new ScopeDeniedError("pin");
        await checkApproval(input.expect, tx, principal, target.id);
        const replacement = await commitNote(
          tx,
          { memoryId, scope: target.scope, principal, pinned, at, text, provenance },
          fingerprint,
        );
        await tx.append({
          format: EVENT_FORMAT,
          kind: "supersede",
          memoryId: target.id,
          scope: target.scope,
          principalId: principal.id,
          by: memoryId,
        });
        await tx.putMemory({ ...target, status: "superseded", supersededBy: memoryId });
        await retractAll(tx, summaries, principal);
        return replacement;
      });
    },

    async sweep(now, approval = {}) {
      if (!Number.isSafeInteger(now) || now < 0) {
        throw new RangeError("sweep takes the time as whole epoch milliseconds");
      }
      if (retention.length === 0) {
        matchPlan(approval.expect, []);
        return Object.freeze({ redacted: [], derived: [] });
      }
      return store.transaction(async (tx) => {
        const redacted: MemoryId[] = [];
        const derived: MemoryId[] = [];
        // No enforceCeiling: retention is the host's policy, run with no principal, and expires
        // owner memories as it does any other.
        const plan = await sweepPlan(tx, retention, await acceptanceTime(tx, now));
        matchPlan(approval.expect, flatten(plan));
        for (const item of plan) {
          redacted.push(item.memory.id);
          derived.push(...(await redactWithDerived(tx, item, "retention", null)));
        }
        return Object.freeze({
          redacted: Object.freeze(redacted),
          derived: Object.freeze(derived),
        });
      });
    },

    async sweepPreview(now) {
      if (!Number.isSafeInteger(now) || now < 0) {
        throw new RangeError("sweep takes the time as whole epoch milliseconds");
      }
      if (retention.length === 0) return Object.freeze([]);
      return store.transaction(async (tx) =>
        Object.freeze(flatten(await sweepPlan(tx, retention, await acceptanceTime(tx, now)))),
      );
    },

    async pending(context, options = {}) {
      const principal = await policy(context);
      const { scope } = options;
      if (scope !== undefined && !principal.readable.includes(scope)) {
        throw new ScopeDeniedError("read");
      }
      const limit = options.limit ?? DEFAULT_RECALL_LIMIT;
      if (!Number.isInteger(limit) || limit < 1) {
        throw new RangeError("pending limit must be a positive integer");
      }
      const scopes = scope === undefined ? principal.readable : [scope];
      const live = await store.liveMemories({ scopes });
      const covered = coveredIds(live);
      return live
        .filter((memory) => !memory.pinned && !isSummary(memory) && !covered.has(memory.id))
        .sort((a, b) => newestFirst(b, a))
        .slice(0, limit);
    },

    async submitSummary(context, input) {
      const { scope, text, opId } = input;
      const principal = await policy(context);
      if (!principal.writable.includes(scope)) throw new ScopeDeniedError("write");
      checkName("scope", scope);
      const sources = checkSources(input.sources);
      guardText(text);
      const fence = principal.fence === undefined ? undefined : checkFence(principal.fence);
      const requestedTrust = input.provenance.trust;
      const provenance = writerProvenance(principal, input.provenance, opId ?? ids.opId());
      const fingerprint = summaryFingerprint({
        scope,
        principalId: principal.id,
        text,
        sources,
        requestedTrust,
        provenance,
      });
      const at = clock.now();
      const memoryId = generatedMemoryId(ids);
      return store.transaction(async (tx) => {
        if (fence !== undefined) await enforceFence(tx, fence);
        const prior = await priorOutcome(tx, principal, provenance.opId, fingerprint);
        if (prior !== undefined) {
          const stored = await tx.memory(prior.memoryId);
          if (stored === undefined || stored.status === "redacted") {
            throw new MemoryRedactedError(prior.memoryId);
          }
          if (!principal.writable.includes(stored.scope)) throw new ScopeDeniedError("write");
          return summaryOutcome(stored);
        }
        let floor: Trust = "owner";
        for (const { memoryId: sourceId, revision } of sources) {
          // Existence first, by the rule every read uses: a reader that does not own the scope
          // sees live memories only, so a retracted, superseded or redacted source is not found.
          const source = visible(principal, await tx.memory(sourceId));
          if (source.scope !== scope) {
            throw new RangeError("every source of a summary must be in the summary's scope");
          }
          if (source.status !== "live" || source.revision.number !== revision) {
            throw new SourceChangedError(sourceId);
          }
          floor = lowerTrust(floor, trustOf(source));
        }
        if (
          requestedTrust !== undefined &&
          lowerTrust(provenance.trust, floor) !== provenance.trust
        ) {
          throw new ProvenanceError("trust", "above-sources");
        }
        const floored: Provenance = Object.freeze({
          ...provenance,
          trust: lowerTrust(provenance.trust, floor),
        });
        const accepted = await acceptanceTime(tx, at);
        const revisionOf: Revision = Object.freeze({ number: 1, text, at, provenance: floored });
        const { seq } = await tx.append({
          format: EVENT_FORMAT,
          kind: "summarize",
          memoryId,
          scope,
          principalId: principal.id,
          sources,
          revision: revisionOf,
        });
        const summary: Memory = Object.freeze({
          id: memoryId,
          scope,
          seq,
          pinned: false,
          notedAt: accepted,
          revision: revisionOf,
          status: "live",
          sources,
        });
        await tx.putMemory(summary);
        await tx.putOp({
          principalId: principal.id,
          opId: provenance.opId,
          fingerprint,
          memoryId,
          at: accepted,
          seq,
        });
        return summary;
      });
    },

    async promote(context, input) {
      const { memoryId: originId, revision, scope, opId } = input;
      const principal = await policy(context);
      checkMemoryId(originId);
      if (!Number.isSafeInteger(revision) || revision < 1) {
        throw new RangeError("a promoted revision must be a positive integer");
      }
      if (!principal.promotable.includes(scope)) throw new ScopeDeniedError("promote");
      checkName("scope", scope);
      const fence = principal.fence === undefined ? undefined : checkFence(principal.fence);
      const requestedTrust = input.provenance.trust;
      const provenance = writerProvenance(principal, input.provenance, opId ?? ids.opId());
      const fingerprint = promoteFingerprint({
        originId,
        revision,
        targetScope: scope,
        principalId: principal.id,
        requestedTrust,
        provenance,
      });
      const at = clock.now();
      const memoryId = generatedMemoryId(ids);
      return store.transaction(async (tx) => {
        if (fence !== undefined) await enforceFence(tx, fence);
        const prior = await priorOutcome(tx, principal, provenance.opId, fingerprint);
        if (prior !== undefined) {
          const stored = await tx.memory(prior.memoryId);
          if (stored === undefined || stored.status === "redacted") {
            throw new MemoryRedactedError(prior.memoryId);
          }
          // Current authority, as the first commit needed it: promote into the copy's scope, and
          // read the origin's scope (the origin is never redacted while its copy is not).
          if (!principal.promotable.includes(stored.scope)) throw new ScopeDeniedError("promote");
          const origin = await tx.memory(stored.origin?.memoryId ?? "");
          if (origin === undefined || !mayRead(principal, origin.scope)) {
            throw new MemoryNotFoundError();
          }
          return promotedOutcome(stored);
        }
        // Existence first, by the rule every read uses: a reader that does not own the origin's
        // scope sees live memories only, so a retracted, superseded or redacted origin is not found.
        const origin = visible(principal, await tx.memory(originId));
        if (origin.scope === scope) {
          throw new RangeError("a memory is promoted into another scope than its own");
        }
        if (origin.status !== "live" || origin.revision.number !== revision) {
          throw new SourceChangedError(originId);
        }
        // A copy of a summary would carry its sources' facts into a scope whose readers cannot
        // see the sources, and be neither a summary nor a cover there.
        if (isSummary(origin)) {
          throw new RangeError("a summary is not promoted: promote its sources instead");
        }
        const floor = trustOf(origin);
        if (
          requestedTrust !== undefined &&
          lowerTrust(provenance.trust, floor) !== provenance.trust
        ) {
          throw new ProvenanceError("trust", "above-sources");
        }
        const floored: Provenance = Object.freeze({
          ...provenance,
          trust: lowerTrust(provenance.trust, floor),
        });
        const text = origin.revision.text;
        const accepted = await acceptanceTime(tx, at);
        const revisionOf: Revision = Object.freeze({ number: 1, text, at, provenance: floored });
        const link = Object.freeze({ memoryId: originId, revision });
        const { seq } = await tx.append({
          format: PROMOTE_FORMAT,
          kind: "promote",
          memoryId,
          scope,
          principalId: principal.id,
          origin: link,
          revision: revisionOf,
        });
        const copy: Memory = Object.freeze({
          id: memoryId,
          scope,
          seq,
          pinned: false,
          notedAt: accepted,
          revision: revisionOf,
          status: "live",
          origin: link,
        });
        await tx.putMemory(copy);
        await tx.putOp({
          principalId: principal.id,
          opId: provenance.opId,
          fingerprint,
          memoryId,
          at: accepted,
          seq,
        });
        return copy;
      });
    },

    async recall(context, recallOptions = {}) {
      const principal = await policy(context);
      const { scope, includeRetracted = false } = recallOptions;
      if (scope !== undefined && !principal.readable.includes(scope)) {
        throw new ScopeDeniedError("read");
      }
      const limit = recallOptions.limit ?? DEFAULT_RECALL_LIMIT;
      if (!Number.isInteger(limit) || limit < 1) {
        throw new RangeError("recall limit must be a positive integer");
      }
      const scopes = scope === undefined ? principal.readable : [scope];
      if (!includeRetracted) return store.recall({ scopes, limit });
      const retracted = scopes.filter((readable) => owns(principal, readable));
      if (retracted.length === 0) throw new ScopeDeniedError("own");
      return store.recall({ scopes, limit, retracted });
    },

    async zoom(context, input) {
      const { memoryId } = input;
      const principal = await policy(context);
      checkMemoryId(memoryId);
      // The store reads one memory by id only inside a transaction.
      return store.transaction(async (tx) => visible(principal, await tx.memory(memoryId)));
    },

    async retract(context, input) {
      const { memoryId } = input;
      const principal = await policy(context);
      checkMemoryId(memoryId);
      const fence = principal.fence === undefined ? undefined : checkFence(principal.fence);
      await store.transaction(async (tx) => {
        if (fence !== undefined) await enforceFence(tx, fence);
        const stored = visible(principal, await tx.memory(memoryId));
        if (!owns(principal, stored.scope)) throw new ScopeDeniedError("own");
        await checkApproval(input.expect, tx, principal, memoryId);
        if (stored.status === "retracted") return;
        if (stored.status !== "live") throw new MemoryStateError(stored.status);
        const summaries = await liveDerived(tx, memoryId);
        enforceCeiling(principal, [stored, ...summaries]);
        await tx.append({
          format: EVENT_FORMAT,
          kind: "retract",
          memoryId,
          scope: stored.scope,
          principalId: principal.id,
        });
        await tx.putMemory({ ...stored, status: "retracted" });
        await retractAll(tx, summaries, principal);
      });
    },

    async redact(context, input) {
      const { memoryId } = input;
      const principal = await policy(context);
      checkMemoryId(memoryId);
      const fence = principal.fence === undefined ? undefined : checkFence(principal.fence);
      return store.transaction(async (tx) => {
        if (fence !== undefined) await enforceFence(tx, fence);
        const plan = await redactionPlan(tx, principal, memoryId);
        const shown = plan === undefined ? [] : shownTo(principal, plan);
        matchPlan(input.expect, shown);
        if (plan === undefined) return { redacted: [], derived: [] };
        enforceCeiling(principal, flatten([plan]));
        const derived = await redactWithDerived(tx, plan, "request", principal.id);
        const listed = new Set(shown.map((memory) => memory.id));
        return { redacted: [memoryId], derived: derived.filter((id) => listed.has(id)) };
      });
    },

    async redactionPreview(context, input) {
      const { memoryId } = input;
      const principal = await policy(context);
      checkMemoryId(memoryId);
      return store.transaction(async (tx) => {
        const plan = await redactionPlan(tx, principal, memoryId);
        return Object.freeze(plan === undefined ? [] : shownTo(principal, plan));
      });
    },

    async find(context, input) {
      return findRanked(await policy(context), input);
    },

    async findRendering(context, input) {
      const principal = await policy(context);
      const carrier = checkCarrier(input.carrier);
      const budgetBytes = checkBudget(input.budgetBytes ?? DEFAULT_BUDGET_BYTES);
      return exposed(carrier, async () => {
        const ranked = await findRanked(principal, input);
        const entries = findEntries(
          ranked.map((result) => result.memory),
          budgetBytes,
        );
        return fitRendering("find", entries, budgetBytes, egress, principal);
      });
    },

    async wake(context, input = {}) {
      const principal = await policy(context);
      const { scope } = input;
      if (scope !== undefined && !principal.readable.includes(scope)) {
        throw new ScopeDeniedError("read");
      }
      const carrier = checkCarrier(input.carrier);
      const budgetBytes = checkBudget(input.budgetBytes ?? DEFAULT_BUDGET_BYTES);
      const scopes = scope === undefined ? principal.readable : [scope];
      return exposed(carrier, async () => {
        const ordered = wakeOrder(await store.liveMemories({ scopes }));
        const entries = wakeEntries(ordered, budgetBytes);
        return fitRendering("wake", entries, budgetBytes, egress, principal);
      });
    },

    async brief(context, input) {
      const principal = await policy(context);
      const { scope, topic } = input;
      if (scope !== undefined && !principal.readable.includes(scope)) {
        throw new ScopeDeniedError("read");
      }
      const carrier = checkCarrier(input.carrier);
      const budgetBytes = checkBudget(input.budgetBytes ?? DEFAULT_BUDGET_BYTES);
      if (typeof topic !== "string" || topic.length > MAX_QUERY_LENGTH) {
        throw new RangeError(
          `a brief topic must be a string of at most ${MAX_QUERY_LENGTH} characters`,
        );
      }
      const scopes = scope === undefined ? principal.readable : [scope];
      return exposed(carrier, async () => {
        const live = hasTokens(topic) ? await store.liveMemories({ scopes }) : [];
        const ranked = rank(topic, live).map((result) => result.memory);
        const entries = briefEntries(ranked, briefSummaries(ranked, live), budgetBytes);
        return fitRendering("brief", entries, budgetBytes, egress, principal);
      });
    },

    async deliverErasures(hook) {
      if (typeof hook !== "function") throw new TypeError("an erasure hook must be a function");
      const counts = { acknowledged: 0, unsupported: 0 };
      const errors: unknown[] = [];
      // Pages by seq: an outcome stored meanwhile never moves a later row into an earlier page.
      for (let after = 0; ; ) {
        const page = await store.pendingErasures({ after, limit: DELIVERY_PAGE });
        for (const row of page) await deliverOne(row);
        const last = page.at(-1);
        if (page.length < DELIVERY_PAGE || last === undefined) break;
        after = last.seq;
      }
      const { carriers: pending } = await store.pendingErasureCount();
      return Object.freeze({ ...counts, pending, errors: Object.freeze(errors) });

      async function deliverOne(row: ErasureWork): Promise<void> {
        const carriers = [...row.carriers]
          .map(({ id, kind }) => Object.freeze({ id, kind }))
          .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
        if (carriers.length === 0) return;
        let receipt: unknown;
        try {
          receipt = await hook(
            Object.freeze({
              seq: row.seq,
              memoryId: row.memoryId,
              carriers: Object.freeze(carriers),
            }),
          );
        } catch (error) {
          errors.push(error);
          return;
        }
        const outcomes = carriers.flatMap((carrier) => {
          const status = outcomeIn(receipt, carrier.id);
          return status === undefined ? [] : [{ carrierId: carrier.id, status }];
        });
        if (outcomes.length === 0) return;
        const at = clock.now();
        await store.transaction(async (tx) => {
          for (const { carrierId, status } of outcomes) {
            await tx.settle({ seq: row.seq, carrierId, status, at });
          }
        });
        for (const { status } of outcomes) counts[status]++;
      }
    },

    async erasureStatus() {
      return erasureStatuses(store);
    },
  };
}

/** How many outbox rows deliverErasures reads per page. */
const DELIVERY_PAGE = 100;

/** How many times a rendering for a carrier is made before ExposureRedactedError. */
const MAX_RENDER_ATTEMPTS = 3;

/** Every outbox row with its carriers' statuses, from the store's outbox and outcomes. */
async function erasureStatuses(store: Store): Promise<readonly ErasureStatus[]> {
  const [work, settlements] = await Promise.all([store.erasures(), store.settlements()]);
  const outcomes = new Map(
    settlements.map((settled) => [
      JSON.stringify([settled.seq, settled.carrierId]),
      settled.status,
    ]),
  );
  return Object.freeze(
    work.map((row) =>
      Object.freeze({
        seq: row.seq,
        memoryId: row.memoryId,
        carriers: Object.freeze(
          row.carriers.map(({ id, kind }) =>
            Object.freeze({
              id,
              kind,
              status: outcomes.get(JSON.stringify([row.seq, id])) ?? ("pending" as const),
            }),
          ),
        ),
      }),
    ),
  );
}

/** The outcome a hook's receipt gives `carrierId`: an own property holding exactly one, or none. */
function outcomeIn(receipt: unknown, carrierId: string): CarrierOutcome | undefined {
  if (typeof receipt !== "object" || receipt === null || !Object.hasOwn(receipt, carrierId)) {
    return undefined;
  }
  const status: unknown = (receipt as Record<string, unknown>)[carrierId];
  return status === "acknowledged" || status === "unsupported" ? status : undefined;
}

/** A rendering's carrier, once both its fields pass the identifier rule; undefined when absent. */
export function checkCarrier(carrier: Carrier | undefined): Carrier | undefined {
  if (carrier === undefined) return undefined;
  if (typeof carrier !== "object" || carrier === null) {
    throw new TypeError("a carrier must be an object with an id and a kind");
  }
  const { id, kind } = carrier;
  if (typeof id !== "string" || typeof kind !== "string") {
    throw new TypeError("a carrier's id and kind must be strings");
  }
  checkName("carrier id", id);
  checkName("carrier kind", kind);
  return Object.freeze({ id, kind });
}

/**
 * Records `fence` as the highest epoch for its key, for a host taking over an authority. Refuses
 * with FencedError when the store already holds a higher epoch; the same epoch again is accepted.
 */
export async function advanceFence(store: Store, fence: AuthorityFence): Promise<void> {
  const checked = checkFence(fence);
  await store.transaction((tx) => enforceFence(tx, checked));
}

/** Refuses a lower epoch than the store holds for the key, and records a higher one. */
export async function enforceFence(tx: StoreTransaction, fence: AuthorityFence): Promise<void> {
  const highest = await tx.fenceEpoch(fence.key);
  if (highest !== undefined && fence.epoch < highest) throw new FencedError();
  if (highest !== fence.epoch) await tx.putFence(fence);
}

/** Copies the fence once, so an accessor cannot answer differently to the check and the store. */
export function checkFence(fence: AuthorityFence): AuthorityFence {
  const { key, epoch } = fence;
  if (typeof key !== "string" || key === "") {
    throw new TypeError("an authority fence key must be a non-empty string");
  }
  checkName("fence key", key);
  if (!Number.isSafeInteger(epoch) || epoch < 0) {
    throw new RangeError("an authority fence epoch must be a non-negative safe integer");
  }
  return Object.freeze({ key, epoch });
}

const DAY_MS = 86_400_000;

/** The retention rules copied once and checked: a valid scope, a positive whole number of days. */
function checkRetention(given: readonly RetentionRule[]): readonly RetentionRule[] {
  if (!Array.isArray(given)) throw new RangeError("retention must be a list of rules");
  const rules = given.map(({ scope, maxAgeDays }) => {
    if (typeof scope !== "string" || scope === "" || utf8Bytes(scope) > MAX_SCOPE_BYTES) {
      throw new RangeError(`a retention scope must be 1 to ${MAX_SCOPE_BYTES} UTF-8 bytes`);
    }
    checkName("scope", scope);
    if (!Number.isSafeInteger(maxAgeDays) || maxAgeDays < 1) {
      throw new RangeError("a retention rule's maxAgeDays must be a positive whole number");
    }
    return Object.freeze({ scope, maxAgeDays });
  });
  if (new Set(rules.map((rule) => rule.scope)).size !== rules.length) {
    throw new RangeError("retention takes at most one rule per scope");
  }
  return Object.freeze(rules);
}

/** The most sources one summary may have. */
export const MAX_SUMMARY_SOURCES = 100;

/**
 * The sources copied once, checked (1 to 100, each a memory id and a positive revision, no memory
 * twice) and sorted by memory id, so the order they were given in changes nothing.
 */
export function checkSources(given: readonly SourceRevision[]): readonly SourceRevision[] {
  if (!Array.isArray(given) || given.length < 1 || given.length > MAX_SUMMARY_SOURCES) {
    throw new RangeError(`a summary needs 1 to ${MAX_SUMMARY_SOURCES} sources`);
  }
  const sources = given.map(({ memoryId, revision }) => {
    checkMemoryId(memoryId);
    if (!Number.isSafeInteger(revision) || revision < 1) {
      throw new RangeError("a source revision must be a positive integer");
    }
    return Object.freeze({ memoryId, revision });
  });
  if (new Set(sources.map((s) => s.memoryId)).size !== sources.length) {
    throw new RangeError("a summary lists each source once");
  }
  return Object.freeze(sources.sort((a, b) => (a.memoryId < b.memoryId ? -1 : 1)));
}

/** A summary's first outcome, as its commit returned it. */
function summaryOutcome(stored: Memory): Memory {
  const { id, scope, seq, notedAt, revision, sources } = stored;
  return Object.freeze({
    id,
    scope,
    seq,
    pinned: false,
    notedAt,
    revision,
    status: "live" as const,
    ...(sources === undefined ? {} : { sources }),
  });
}

/** A promoted copy's first outcome, as its commit returned it. */
function promotedOutcome(stored: Memory): Memory {
  const { id, scope, seq, notedAt, revision, origin } = stored;
  return Object.freeze({
    id,
    scope,
    seq,
    pinned: false,
    notedAt,
    revision,
    status: "live" as const,
    ...(origin === undefined ? {} : { origin }),
  });
}

interface NewMemory {
  readonly memoryId: MemoryId;
  readonly scope: Scope;
  readonly principal: Principal;
  readonly pinned: boolean;
  readonly at: number;
  readonly text: string;
  readonly provenance: Provenance;
}

/**
 * Appends the note event of a new memory at revision 1, puts the memory, and stores its op record
 * with `fingerprint` and the generated id, time and seq, all in the caller's transaction.
 */
async function commitNote(
  tx: StoreTransaction,
  write: NewMemory,
  fingerprint: string,
): Promise<Memory> {
  const { memoryId, scope, principal, pinned, at, text, provenance } = write;
  const revision: Revision = Object.freeze({ number: 1, text, at, provenance });
  const event: NewEvent = {
    format: EVENT_FORMAT,
    kind: "note",
    memoryId,
    scope,
    principalId: principal.id,
    pinned,
    revision,
  };
  const accepted = await acceptanceTime(tx, at);
  const { seq } = await tx.append(event);
  const memory = noted(memoryId, scope, seq, pinned, { notedAt: accepted, at }, text, provenance);
  await tx.putMemory(memory);
  await tx.putOp({
    principalId: principal.id,
    opId: provenance.opId,
    fingerprint,
    memoryId,
    at: accepted,
    seq,
  });
  return memory;
}

/**
 * The principal's earlier outcome for `opId`, when the same request was committed before.
 * Redaction overrides it (MemoryRedactedError: no fingerprint is left to compare against), and a
 * different payload under the op id is an OpConflictError.
 */
async function priorOutcome(
  tx: StoreTransaction,
  principal: Principal,
  opId: OpId,
  fingerprint: string,
): Promise<OpRecord | undefined> {
  const prior = await tx.op(principal.id, opId);
  if (prior === undefined) return undefined;
  if (await isRedacted(tx, prior)) throw new MemoryRedactedError(prior.memoryId);
  if (prior.fingerprint !== fingerprint) throw new OpConflictError();
  return prior;
}

/**
 * The stored provenance of a write: the known fields only, each screened, with trust defaulted to
 * `agent` (or the principal's lower ceiling) and never above the ceiling.
 */
function writerProvenance(principal: Principal, given: NoteProvenance, opId: OpId): Provenance {
  // Copy every field once, so an accessor cannot answer differently to the checks and the store.
  const { agent, harness, model, host, source, trust } = given;
  const ceiling = trustCeiling(principal);
  return checkProvenance({
    agent,
    harness,
    model,
    host,
    ...(source === undefined ? {} : { source }),
    trust: checkTrust(trust ?? lowerTrust(DEFAULT_TRUST, ceiling), ceiling),
    opId,
  });
}

/**
 * A memory id from the Ids port, refused unless rendering could show it: the host is trusted, so
 * a bad id is a host bug, refused loudly (IdentifierError) before anything is written.
 */
function generatedMemoryId(ids: Ids): MemoryId {
  const memoryId = ids.memoryId();
  if (typeof memoryId !== "string" || memoryId === "" || utf8Bytes(memoryId) > MAX_ID_BYTES) {
    throw new TypeError(`the Ids port must return a memory id of 1 to ${MAX_ID_BYTES} UTF-8 bytes`);
  }
  checkName("memory id", memoryId);
  return memoryId;
}

/** Whether the memory an op record names was redacted, so its outcome can no longer be returned. */
async function isRedacted(tx: StoreTransaction, record: OpRecord): Promise<boolean> {
  if (record.fingerprint === undefined) return true;
  return (await tx.memory(record.memoryId))?.status === "redacted";
}

/**
 * Every memory derived from `memoryId`, directly or through others, that still has its text (not
 * redacted), each once, nearest first: the summaries, and with `copies` the promoted copies too,
 * with what is derived from them in turn. Redaction follows copies, since erasure reaches every
 * copy relembra made; retraction and supersession do not, since a copy lives in a scope with its
 * own owners.
 */
async function derivedClosure(
  tx: StoreTransaction,
  memoryId: MemoryId,
  copies: boolean,
): Promise<Memory[]> {
  const found: Memory[] = [];
  const seen = new Set([memoryId]);
  const queue = [memoryId];
  for (let id = queue.shift(); id !== undefined; id = queue.shift()) {
    for (const derivedId of await tx.derived(id)) {
      if (seen.has(derivedId)) continue;
      seen.add(derivedId);
      const derived = await tx.memory(derivedId);
      if (derived === undefined || derived.status === "redacted") continue;
      if (!copies && derived.origin !== undefined) continue;
      found.push(derived);
      queue.push(derivedId);
    }
  }
  return found;
}

/**
 * The part of a redaction plan `principal` may see, in plan order: the memory, and each derived
 * memory in a scope it owns, or live in a scope it reads. Summaries share their source's scope,
 * which the redacting owner owns; a promoted copy may live in a scope it cannot read, and is then
 * redacted without being shown. Previews, approvals and a redaction's result use this list.
 */
function shownTo(principal: Principal, { memory, derived }: RedactionItem): Memory[] {
  return [memory, ...derived.filter((other) => visibleTo(principal, other))];
}

/** Whether `principal` may see `memory`: any status in a scope it owns, live in one it reads. */
export function visibleTo(principal: Principal, memory: StoredMemory): boolean {
  return (
    owns(principal, memory.scope) ||
    (memory.status === "live" && principal.readable.includes(memory.scope))
  );
}

function mayRead(principal: Principal, scope: Scope): boolean {
  return owns(principal, scope) || principal.readable.includes(scope);
}

/** A memory to redact and the summaries and promoted copies derived from it that go with it. */
interface RedactionItem {
  readonly memory: Memory;
  readonly derived: readonly Memory[];
}

/**
 * What redact erases, under its checks: the memory and its derived closure (summaries and
 * promoted copies), or undefined for a tombstone. Shared by redact and redactionPreview, which
 * both show it through shownTo, so a preview is exactly what the redaction shows.
 */
export async function redactionPlan(
  tx: StoreTransaction,
  principal: Principal,
  memoryId: MemoryId,
): Promise<RedactionItem | undefined> {
  const stored = visible(principal, await tx.memory(memoryId));
  if (!owns(principal, stored.scope)) throw new ScopeDeniedError("own");
  if (stored.status === "redacted") return undefined;
  return { memory: stored, derived: await derivedClosure(tx, stored.id, true) };
}

/**
 * What sweep(now) redacts, in its order: each expired memory once (any status but redacted,
 * noted before the scope's cutoff, exclusive) with the summaries and promoted copies derived from
 * it that no earlier item covers. Shared by sweep and sweepPreview, so a preview is exactly the
 * sweep.
 */
async function sweepPlan(
  tx: StoreTransaction,
  retention: readonly RetentionRule[],
  now: number,
): Promise<RedactionItem[]> {
  const plan: RedactionItem[] = [];
  const covered = new Set<MemoryId>();
  for (const { scope, maxAgeDays } of retention) {
    for (const expired of await tx.expiring(scope, now - maxAgeDays * DAY_MS)) {
      // A summary may already be covered as derived from an earlier expired source.
      if (covered.has(expired.id)) continue;
      const current = await tx.memory(expired.id);
      if (current === undefined || current.status === "redacted") continue;
      covered.add(current.id);
      const derived = (await derivedClosure(tx, current.id, true)).filter(
        (s) => !covered.has(s.id),
      );
      for (const summary of derived) covered.add(summary.id);
      plan.push({ memory: current, derived });
    }
  }
  return plan;
}

function flatten(plan: readonly RedactionItem[]): Memory[] {
  return plan.flatMap((item) => [item.memory, ...item.derived]);
}

/**
 * Throws PlanChangedError unless `planned` is the set `expected` lists, matched by id with every
 * field of each record deep-equal (isDeepStrictEqual: NaN, -0, undefined in arrays, a missing
 * field and a cycle all compare as themselves, and a field added later is compared without being
 * listed). An approval that cannot be compared at all is a changed plan too, never another error.
 * No check without an approval.
 */
function matchPlan(expected: readonly Memory[] | undefined, planned: readonly Memory[]): void {
  if (expected === undefined) return;
  let same = false;
  try {
    same = approves(expected, planned);
  } catch {
    // An approval that cannot be read or compared approves nothing.
  }
  if (!same) throw new PlanChangedError();
}

/**
 * Whether `expected` lists exactly the records of `planned`, each once. The approval is copied
 * into a plain array in one pass first, so a getter or a Proxy cannot change it between the
 * checks. The copy is read slot by slot with an index, never with map, every or a Set, which
 * skip a hole or count it as `undefined`: a sparse approval would then approve records it does
 * not hold. Every slot must be an object with a string id that the plan has, deep-equal to the
 * planned record, and every planned record must be approved exactly once.
 */
function approves(expected: readonly unknown[], planned: readonly Memory[]): boolean {
  if (!Array.isArray(expected)) return false;
  const slots: unknown[] = Array.prototype.slice.call(expected);
  const count = slots.length;
  if (count !== planned.length) return false;
  const byId = new Map<string, Memory>();
  for (const memory of planned) byId.set(memory.id, memory);
  if (byId.size !== planned.length) return false;
  const seen = new Set<string>();
  for (let i = 0; i < count; i++) {
    if (!Object.hasOwn(slots, i)) return false;
    const memory: unknown = slots[i];
    if (typeof memory !== "object" || memory === null) return false;
    const id: unknown = (memory as { id?: unknown }).id;
    if (typeof id !== "string" || seen.has(id)) return false;
    seen.add(id);
    const current = byId.get(id);
    if (current === undefined || !isDeepStrictEqual(memory, current)) return false;
  }
  return seen.size === planned.length;
}

/**
 * Retract and supersede are approved against what redactionPreview lists: the memory and its
 * derived closure.
 */
async function checkApproval(
  expected: readonly Memory[] | undefined,
  tx: StoreTransaction,
  principal: Principal,
  memoryId: MemoryId,
): Promise<void> {
  if (expected === undefined) return;
  const plan = await redactionPlan(tx, principal, memoryId);
  matchPlan(expected, plan === undefined ? [] : shownTo(principal, plan));
}

/**
 * Redacts a planned memory and the summaries and promoted copies derived from it, in the caller's
 * transaction, and returns the derived memories' ids. Each gets a redact event, its tombstone (the
 * store scrubs its text, events and op fingerprints) and an outbox row naming the carriers recorded
 * as having received it.
 */
export async function redactWithDerived(
  tx: StoreTransaction,
  { memory, derived }: RedactionItem,
  cause: RedactionCause,
  principalId: string | null,
): Promise<MemoryId[]> {
  await redactOne(tx, memory, cause, principalId);
  for (const summary of derived) await redactOne(tx, summary, "source", principalId);
  return derived.map((summary) => summary.id);
}

async function redactOne(
  tx: StoreTransaction,
  memory: Memory,
  cause: RedactionCause,
  principalId: string | null,
): Promise<void> {
  const { seq } = await tx.append({
    format: EVENT_FORMAT,
    kind: "redact",
    memoryId: memory.id,
    scope: memory.scope,
    cause,
    principalId,
  });
  const carriers = [...(await tx.exposures(memory.id))]
    .map(({ id, kind }) => ({ id, kind }))
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  await tx.redact({ id: memory.id, scope: memory.scope, seq, status: "redacted" });
  await tx.putErasure({ seq, memoryId: memory.id, carriers });
}

/**
 * What retract and supersede retract besides the memory itself: the live summaries derived from
 * it, transitively, since a summary carries its sources' facts; never a promoted copy, which
 * lives in a scope with its own owners. Both check the trust ceiling
 * against this list and then retract exactly this list, so the check and the write cannot drift.
 */
export async function liveDerived(tx: StoreTransaction, memoryId: MemoryId): Promise<Memory[]> {
  return (await derivedClosure(tx, memoryId, false)).filter((summary) => summary.status === "live");
}

/** Retracts each of `summaries` (from liveDerived), in the caller's transaction. */
export async function retractAll(
  tx: StoreTransaction,
  summaries: readonly Memory[],
  principal: Principal,
): Promise<void> {
  for (const summary of summaries) {
    await tx.append({
      format: EVENT_FORMAT,
      kind: "retract",
      memoryId: summary.id,
      scope: summary.scope,
      principalId: principal.id,
    });
    await tx.putMemory({ ...summary, status: "retracted" });
  }
}

export function owns(principal: Principal, scope: Scope): boolean {
  return (principal.owned ?? []).includes(scope);
}

/**
 * `stored` when `principal` may see it: any status in a scope it owns, a live memory in a scope
 * it reads. MemoryNotFoundError otherwise, the same refusal as for an id that does not exist.
 */
function visible(principal: Principal, stored: StoredMemory | undefined): StoredMemory {
  if (stored === undefined || !visibleTo(principal, stored)) throw new MemoryNotFoundError();
  return stored;
}

function checkMemoryId(memoryId: unknown): void {
  if (typeof memoryId !== "string") throw new TypeError("a memory id must be a string");
  checkName("memory id", memoryId);
}

/** The most UTF-8 bytes a principal id may have. */
export const MAX_PRINCIPAL_ID_BYTES = 256;
/** The most UTF-8 bytes an authority fence key may have. */
const MAX_FENCE_KEY_BYTES = 256;

/** The most UTF-8 bytes a carrier id may have. */
export const MAX_CARRIER_ID_BYTES = 512;
/** The most UTF-8 bytes a carrier kind may have. */
export const MAX_CARRIER_KIND_BYTES = 64;

const NAME_MAX_BYTES: Readonly<Record<NamingField, number>> = {
  scope: MAX_SCOPE_BYTES,
  "memory id": MAX_ID_BYTES,
  "principal id": MAX_PRINCIPAL_ID_BYTES,
  "fence key": MAX_FENCE_KEY_BYTES,
  "carrier id": MAX_CARRIER_ID_BYTES,
  "carrier kind": MAX_CARRIER_KIND_BYTES,
};

/**
 * The identifier rule, for every scope, principal id, memory id, fence key and carrier the library
 * takes:
 * well-formed UTF-16 (IllFormedStringError), then the guard's rules within the field's byte cap
 * (IdentifierError): not blank, one line, no control, format, bidi, zero-width or other invisible
 * character (the emoji joiners the guard allows excepted), no credential shape.
 */
export function checkName(field: NamingField, value: string): void {
  checkWellFormed(field, value);
  const rule = findGuardViolation(value, NAME_MAX_BYTES[field]);
  if (rule !== undefined) throw new IdentifierError(field, rule);
}

/**
 * Refuses a name holding a lone surrogate (IllFormedStringError): encoded as UTF-8 it becomes
 * U+FFFD, so two different names would be one in a store, a hash or a file.
 */
function checkWellFormed(field: NamingField, value: string): void {
  if (!value.isWellFormed()) throw new IllFormedStringError(field);
}

/**
 * `principal`, once its id and every scope it lists are checked to be strings that pass the
 * identifier rule (checkName). Called on every principal a policy gives, and by the functions
 * that take a principal directly.
 */
export function checkPrincipal(principal: Principal): Principal {
  if (typeof principal.id !== "string") throw new TypeError("a principal id must be a string");
  checkName("principal id", principal.id);
  const { readable, writable, promotable, pinnable = [], owned = [] } = principal;
  for (const scopes of [readable, writable, promotable, pinnable, owned]) {
    for (const scope of scopes) {
      if (typeof scope !== "string") throw new TypeError("a principal's scopes must be strings");
      checkName("scope", scope);
    }
  }
  return principal;
}

/** A write's two times: when the store accepted it, and what the caller's Clock read. */
interface WriteTimes {
  readonly notedAt: number;
  readonly at: number;
}

/** A memory at revision 1, as a note commits it. */
function noted(
  id: string,
  scope: Scope,
  seq: number,
  pinned: boolean,
  { notedAt, at }: WriteTimes,
  text: string,
  provenance: Provenance,
): Memory {
  const revision: Revision = Object.freeze({ number: 1, text, at, provenance });
  return Object.freeze({ id, scope, seq, pinned, notedAt, revision, status: "live" as const });
}

/**
 * The time a write is accepted at: the store's own time when it keeps one (StoreTransaction.now),
 * otherwise `callerNow`, the Clock's reading.
 */
export async function acceptanceTime(tx: StoreTransaction, callerNow: number): Promise<number> {
  if (tx.now === undefined) return callerNow;
  const now = await tx.now();
  if (!Number.isSafeInteger(now) || now < 0) {
    throw new TypeError("a store's time must be whole, non-negative epoch milliseconds");
  }
  return now;
}

/**
 * The times of the write `prior` records, as first committed. The op record keeps the acceptance
 * time; the caller's time is the memory's revision.at, which equals it on a store without a time
 * of its own. `priorOutcome` has refused a redacted memory already.
 */
async function firstTimes(tx: StoreTransaction, prior: OpRecord): Promise<WriteTimes> {
  const stored = await tx.memory(prior.memoryId);
  const at = stored === undefined || stored.status === "redacted" ? prior.at : stored.revision.at;
  return { notedAt: prior.at, at };
}

/** Trust tiers from least to most trusted. */
const TRUST_ORDER: readonly Trust[] = ["untrusted", "agent", "owner"];
const DEFAULT_TRUST: Trust = "agent";

/**
 * Refuses, with ProvenanceError("trust", "above-ceiling") and before anything is written, a
 * principal's change to any of `memories` whose trust is above its trust ceiling. Each change
 * passes every memory it would change: redact the target and its derived closure, retract and
 * supersede the target and its live derived summaries (liveDerived). An event replay can call it
 * the same way.
 * Previews do not: a host previews at its usual ceiling, asks a person, then acts at a raised one.
 * Retention sweep is exempt.
 */
export function enforceCeiling(principal: Principal, memories: readonly Memory[]): void {
  const ceiling = trustCeiling(principal);
  for (const memory of memories) {
    const trust = trustOf(memory);
    if (lowerTrust(trust, ceiling) !== trust) throw new ProvenanceError("trust", "above-ceiling");
  }
}

/** The principal's ceiling, `agent` when unset. A ceiling outside the tiers is a host bug. */
export function trustCeiling(principal: Principal): Trust {
  const ceiling = principal.trustCeiling ?? DEFAULT_TRUST;
  if (!TRUST_ORDER.includes(ceiling)) {
    throw new TypeError("the policy returned a trust ceiling that is not a trust tier");
  }
  return ceiling;
}

export function lowerTrust(a: Trust, b: Trust): Trust {
  return TRUST_ORDER.indexOf(a) <= TRUST_ORDER.indexOf(b) ? a : b;
}

/** A write may lower its trust, never raise it above the principal's ceiling. */
function checkTrust(trust: unknown, ceiling: Trust): Trust {
  const rank = TRUST_ORDER.indexOf(trust as Trust);
  if (rank === -1) throw new ProvenanceError("trust", "unknown-tier");
  if (rank > TRUST_ORDER.indexOf(ceiling)) throw new ProvenanceError("trust", "above-ceiling");
  return trust as Trust;
}

const OP_ID_MAX_BYTES = 256;
const PROVENANCE_MAX_BYTES = 128;

/**
 * Builds the stored provenance from the known fields only, each screened by the guard (one line,
 * nothing invisible, no credential) within its byte cap. `source` is optional.
 */
export function checkProvenance(provenance: Provenance): Provenance {
  const { agent, harness, model, host, source, trust, opId } = provenance;
  screen("agent", agent, PROVENANCE_MAX_BYTES);
  screen("harness", harness, PROVENANCE_MAX_BYTES);
  screen("model", model, PROVENANCE_MAX_BYTES);
  screen("host", host, PROVENANCE_MAX_BYTES);
  if (source !== undefined) screen("source", source, PROVENANCE_MAX_BYTES);
  screen("opId", opId, OP_ID_MAX_BYTES);
  return Object.freeze({
    agent,
    harness,
    model,
    host,
    ...(source === undefined ? {} : { source }),
    trust,
    opId,
  });
}

function screen(field: ProvenanceField, value: unknown, maxBytes: number): void {
  if (typeof value !== "string") throw new ProvenanceError(field, "missing");
  const rule = findGuardViolation(value, maxBytes);
  if (rule !== undefined) throw new ProvenanceError(field, rule);
}
