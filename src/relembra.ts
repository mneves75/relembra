/**
 * The preview a person approved, for a host that gates a mutation on it. The mutation re-plans in
 * its own transaction and, when the memories it would change differ from these in any field
 * (text, scope, provenance, status, revision and the rest), writes nothing and throws
 * PlanChangedError. It guards a confirmed plan against concurrent writers, not against a hostile
 * caller, which could simply leave `expect` out.
 */
export interface Approval {
  /** What sweepPreview or redactionPreview returned; no check when absent. */
  readonly expect?: readonly Memory[];
}

