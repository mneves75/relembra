export interface RelembraOptions<Context> {
  readonly store: Store;
  readonly policy: Policy<Context>;
  readonly clock?: Clock;
  readonly ids?: Ids;
  /**
   * Runs on every wake, brief and find rendering for the principal it is for. The identity
   * filter when absent.
   */
  readonly egress?: EgressFilter;
  /** What sweep redacts: at most one rule per scope. Nothing expires when absent. */
  readonly retention?: readonly RetentionRule[];
}

/** Memories in `scope` first noted more than `maxAgeDays` days before a sweep are redacted. */
export interface RetentionRule {
  readonly scope: Scope;
  /** A positive whole number of days. */
  readonly maxAgeDays: number;
}

/**
 * Provenance as the writer supplies it; the op id is passed beside it. `trust` defaults to `agent`,
 * or to the principal's ceiling when that is lower.
 */
export type NoteProvenance = Omit<Provenance, "opId" | "trust"> & { readonly trust?: Trust };

